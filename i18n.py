def is_rtl(lang):
    return lang in RTL_LANGUAGES


def translate(text, lang):
    text = "" if text is None else str(text)
    if lang != "en":
        return text
    if text in TRANSLATIONS:
        return TRANSLATIONS[text]
    for fa, en in PREFIXES:
        if text.startswith(fa):
            return en + text[len(fa):]
    return text


